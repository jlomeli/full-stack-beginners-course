// Generates SYLLABUS.md and any missing lesson folders from curriculum.json.
// Usage: node scripts/build.mjs [--check]
// --check writes nothing and exits 1 when SYLLABUS.md is stale or a lesson folder is missing.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const check = process.argv.includes('--check');
const curriculum = JSON.parse(readFileSync(join(root, 'curriculum.json'), 'utf8'));

const lessons = curriculum.modules.flatMap((module) => module.lessons.map((lesson) => ({ ...lesson, module: module.title })));

lessons.forEach((lesson, index) => {
	const expectedId = String(index).padStart(2, '0');
	if (lesson.id !== expectedId) throw new Error(`Lesson "${lesson.title}" has id ${lesson.id}, expected ${expectedId}`);
	if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(lesson.slug)) throw new Error(`Lesson ${lesson.id} slug "${lesson.slug}" is not kebab-case`);
});

const perWeek = curriculum.sessionsPerWeek;
let session = 0;
for (const lesson of lessons) {
	const sessions = lesson.sessions ?? 1;
	lesson.firstWeek = Math.floor(session / perWeek) + 1;
	lesson.lastWeek = Math.floor((session + sessions - 1) / perWeek) + 1;
	session += sessions;
}
const totalWeeks = lessons.at(-1).lastWeek;

const folder = (lesson) => `lessons/${lesson.id}-${lesson.slug}`;
const weekLabel = (lesson) => (lesson.firstWeek === lesson.lastWeek ? `${lesson.firstWeek}` : `${lesson.firstWeek}-${lesson.lastWeek}`);
const bullets = (items) => items.map((item) => `- ${item}`).join('\n');

const syllabus = `# ${curriculum.title} syllabus

<!-- Generated by \`node scripts/build.mjs\` from curriculum.json. Edit curriculum.json, not this file. -->

${lessons.length} lessons over ${totalWeeks} weeks at ${curriculum.sessionsPerWeek} sessions a week. Most lessons take one session. Lessons marked **Project** take several sessions and end with a larger build that you submit as its own pull request.

Stack: ${curriculum.stack.join(', ')}.

| Lesson | Title | Week | Branch |
| --- | --- | --- | --- |
${lessons.map((l) => `| [${l.id}](${folder(l)}) | ${l.title}${l.project ? ' **Project**' : ''} | ${weekLabel(l)} | \`lesson-${l.id}\` |`).join('\n')}

${curriculum.modules
	.map(
		(module) => `## ${module.title}

${module.lessons
	.map((l) => {
		const lesson = lessons.find((x) => x.id === l.id);
		return `### ${lesson.id}. ${lesson.title}

Week ${weekLabel(lesson)}. Folder [\`${folder(lesson)}\`](${folder(lesson)}).

You will be able to:

${bullets(lesson.objectives)}

Exercises:

${bullets(lesson.exercises)}`;
	})
	.join('\n\n')}`,
	)
	.join('\n\n')}
`;

const lessonReadme = (lesson) => `# ${lesson.id}. ${lesson.title}

> Draft. Generated from curriculum.json. Replace this note with the lesson.

## What you will be able to do

${bullets(lesson.objectives)}

## Lesson

TODO

## Exercises

${lesson.exercises.map((exercise, i) => `${i + 1}. ${exercise}`).join('\n')}

## Submit

Work on the \`lesson-${lesson.id}\` branch and open a pull request. See [how to submit your work](../../docs/student-workflow.md).
`;

const problems = [];
const syllabusPath = join(root, 'SYLLABUS.md');
if (!existsSync(syllabusPath) || readFileSync(syllabusPath, 'utf8') !== syllabus) {
	if (check) problems.push('SYLLABUS.md is out of date. Run `node scripts/build.mjs`.');
	else writeFileSync(syllabusPath, syllabus);
}

for (const lesson of lessons) {
	const dir = join(root, folder(lesson));
	if (existsSync(join(dir, 'README.md'))) continue;
	if (check) {
		problems.push(`${folder(lesson)}/README.md is missing. Run \`node scripts/build.mjs\`.`);
		continue;
	}
	mkdirSync(dir, { recursive: true });
	writeFileSync(join(dir, 'README.md'), lessonReadme(lesson));
	console.log(`created ${folder(lesson)}/README.md`);
}

if (problems.length) {
	console.error(problems.join('\n'));
	process.exit(1);
}
console.log(`${lessons.length} lessons, ${totalWeeks} weeks. ${check ? 'Up to date.' : 'SYLLABUS.md written.'}`);
